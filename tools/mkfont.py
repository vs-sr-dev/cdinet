#!/usr/bin/env python3
"""BDF font -> C table for the CD-i: one byte per pixel row, characters 0x20-0xFF.

    python mkfont.py 6x10.bdf font.c

The cell is the font's bounding box (6 x 10 for misc-fixed 6x10, which is in the public
domain); pixels are bits 7 (leftmost) down to 2. Characters the font lacks are left
blank."""
import sys

FIRST, LAST = 0x20, 0xFF


def main():
    src, dst = sys.argv[1], sys.argv[2]
    lines = open(src, encoding="latin-1").read().splitlines()
    cw = ch = asc = None
    glyphs = {}
    i = 0
    while i < len(lines):
        f = lines[i].split()
        if f and f[0] == "FONTBOUNDINGBOX":
            cw, ch, _, by = map(int, f[1:5])
            asc = ch + by
        elif f and f[0] == "STARTCHAR":
            code = bbx = None
            bitmap = []
            while True:
                i += 1
                g = lines[i].split()
                if g[0] == "ENCODING":
                    code = int(g[1])
                elif g[0] == "BBX":
                    bbx = list(map(int, g[1:5]))
                elif g[0] == "BITMAP":
                    while True:
                        i += 1
                        if lines[i].startswith("ENDCHAR"):
                            break
                        bitmap.append(lines[i].strip())
                    break
            if code is not None and FIRST <= code <= LAST:
                w, h, xo, yo = bbx
                rows = [0] * ch
                top = asc - (yo + h)
                for r, hx in enumerate(bitmap):
                    bits = int(hx, 16) >> (len(hx) * 4 - w)       # w bits, leftmost first
                    y = top + r
                    if 0 <= y < ch:
                        v = 0
                        for x in range(w):
                            if bits & (1 << (w - 1 - x)) and 0 <= xo + x < 8:
                                v |= 0x80 >> (xo + x)
                        rows[y] = v
                glyphs[code] = rows
        i += 1
    assert cw <= 6, "the CD-i code draws 6-pixel cells"
    # On a CD-i's wide pixels misc-fixed's plus-shaped full stop reads as a comma: square
    # dots instead (rows from the top of the 10-row cell).
    if ch == 10:
        dot = 0x30
        glyphs[ord(".")] = [0, 0, 0, 0, 0, 0, dot, dot, 0, 0]
        glyphs[ord(":")] = [0, 0, dot, dot, 0, 0, dot, dot, 0, 0]
        glyphs[ord(";")] = [0, 0, dot, dot, 0, 0, dot, dot, 0x10, 0x20]
    with open(dst, "w", newline="\n") as o:
        o.write("/* cdiNet - generated by tools/mkfont.py from %s (public domain), do not edit.\n"
                " * %d x %d cells, characters 0x%02X-0x%02X, one byte per row, bit 7 = left. */\n"
                % (src.replace("\\", "/").rsplit("/", 1)[-1], cw, ch, FIRST, LAST))
        o.write("unsigned char font[%d][%d] = {\n" % (LAST - FIRST + 1, ch))
        for c in range(FIRST, LAST + 1):
            rows = glyphs.get(c, [0] * ch)
            o.write("\t{ %s },\t/* %02X */\n" % (", ".join("0x%02x" % v for v in rows), c))
        o.write("};\n")
    print("%s: %d glyphs, %dx%d" % (dst, len(glyphs), cw, ch))


if __name__ == "__main__":
    main()
